import { describe, expect, test } from 'bun:test';
import { outputSchemaFor, presets, publicPresets } from './presets';

describe('presets', () => {
  test('there are 2–3 presets with unique ids', () => {
    expect(presets.length).toBeGreaterThanOrEqual(2);
    expect(presets.length).toBeLessThanOrEqual(3);
    expect(new Set(presets.map((preset) => preset.id)).size).toBe(presets.length);
  });

  test('each output schema is a strict object schema generated by zod', () => {
    for (const preset of presets) {
      const schema = outputSchemaFor(preset);
      expect(schema.type).toBe('object');
      expect(schema.additionalProperties).toBe(false);
      expect(schema).not.toHaveProperty('$schema');
      expect(schema.required).toEqual(Object.keys(schema.properties as object));
    }
  });

  test('the same schema validates task output', () => {
    const hotel = presets.find((preset) => preset.id === 'cheapest-hotel')!;
    const good = {
      hotelName: 'Casa',
      pricePerNight: '€80',
      totalPrice: '€240',
      rating: '8.1',
      sourceSite: 'Example',
      notes: [],
    };
    expect(hotel.output.safeParse(good).success).toBe(true);
    expect(hotel.output.safeParse({ ...good, notes: 'none' }).success).toBe(false);
    expect(hotel.output.safeParse({ ...good, extra: 1 }).success).toBe(false);
    expect(hotel.output.safeParse({ hotelName: { nested: true } }).success).toBe(false);
  });

  test('the public view carries labels and field types, nothing else', () => {
    const flights = publicPresets(presets).find((preset) => preset.id === 'flight-deals');
    expect(flights?.fields).toContainEqual({ key: 'options', label: 'Top options', type: 'list' });
    expect(flights?.fields).toContainEqual({ key: 'cheapest', label: 'Cheapest', type: 'text' });
    expect(JSON.stringify(publicPresets(presets))).not.toContain('instruction');
  });
});
